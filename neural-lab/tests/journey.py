"""Check the real computations and meanings shown by the public guided route."""
import json,sys
from pathlib import Path
from datetime import datetime,timezone
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
BASE=sys.argv[1] if len(sys.argv)>1 else 'http://127.0.0.1:8766/neural-lab/'
report={'executed_utc':datetime.now(timezone.utc).isoformat(),'url':BASE,'checks':[],'errors':[]}
def check(name,ok):
    assert ok,name
    report['checks'].append({'name':name,'passed':True})
with sync_playwright() as p:
    b=p.chromium.launch(executable_path=r'C:\Program Files\Google\Chrome\Application\chrome.exe',headless=True,args=['--enable-unsafe-swiftshader'])
    page=b.new_page(viewport={'width':1536,'height':1100})
    page.on('pageerror',lambda e:report['errors'].append(str(e)))
    page.goto(BASE);page.wait_for_function('!!window.Journey')
    check('guided route opens by default',page.locator('body').evaluate("e=>e.classList.contains('guided')"))
    check('model starts transparently untrained','non entraîné' in page.locator('#j-weights').inner_text())
    page.locator('#j-ready').click();page.wait_for_function('Journey.model.updates===2000')
    check('actual trained checkpoint loads',page.evaluate('Journey.model.updates')==2000)
    weights=page.evaluate('Journey.model.weights.slice()')
    page.locator('#j-input').fill('al a')
    page.locator('#j-next').click()
    check('tokenization includes space as a token','␠' in page.locator('#j-evidence').inner_text())
    page.locator('#scene').screenshot(path=str(ROOT/'validation/guided-tokenization.png'))
    page.locator('#j-next').click()
    check('IDs match actual vocabulary',page.evaluate("JSON.stringify(Journey.trace.tokens)===JSON.stringify(Array.from('al a').map(c=>Journey.model.vocab.indexOf(c)))"))
    page.locator('#j-next').click();page.locator('[data-token="0"]').click()
    check('embedding is selected by actual token ID',page.evaluate('Journey.selected===0') and 'Ligne 4' in page.locator('#j-evidence').inner_text())
    page.locator('#scene').screenshot(path=str(ROOT/'validation/guided-lookup.png'))
    check('colours have stable roles',page.evaluate("Lab.scene.pickables.some(m=>(Array.isArray(m.material)?m.material[0]:m.material).color.getHex()===0x7451b8)&&Lab.scene.pickables.some(m=>(Array.isArray(m.material)?m.material[0]:m.material).color.getHex()===0x2563a6)"))
    page.locator('#j-next').click()
    check('mask and future positions visible','futur masqué' in page.locator('#j-evidence').inner_text())
    page.locator('#j-next').click()
    check('probabilities visible before choosing',page.evaluate('Journey.chosen===null') and page.locator('.j-prob').count()>0)
    page.locator('#j-next').click()
    check('selection is actual argmax',page.evaluate('Journey.chosen===Journey.trace.probabilities.indexOf(Math.max(...Journey.trace.probabilities))'))
    page.locator('#j-next').click()
    check('inference leaves weights fixed',page.evaluate('Journey.model.weights')==weights)
    check('continuation is explicit',page.locator('#j-again').count()==1)
    page.locator('#j-again').click();check('generation loops back to reading',page.evaluate('Journey.index')==0)
    page.locator('#j-train').click();page.locator('#j-reset').click()
    original=page.evaluate('Journey.model.weights.slice()')
    for _ in range(7):page.locator('#j-next').click()
    check('known target used for loss',page.evaluate("Journey.model.vocab[Journey.trace.target]==='p'"))
    check('weights fixed until correction',page.evaluate('Journey.model.weights')==original)
    page.locator('#j-next').click();check('gradients really computed',page.evaluate('Journey.trace.gradientComputed'))
    page.locator('#j-next').click();check('update really executed once',page.evaluate('Journey.model.updates')==1 and page.evaluate('Journey.model.weights')!=original)
    updated=page.evaluate('Journey.model.weights.slice()')
    page.locator('#j-prev').click();page.locator('#j-next').click();check('replay does not double-update',page.evaluate('Journey.model.updates')==1 and page.evaluate('Journey.model.weights')==updated)
    page.locator('#j-next').click();check('same-example before/after measured',page.evaluate('Journey.after.tape.v[Journey.after.loss]<Journey.trace.tape.v[Journey.trace.loss]'))
    report['manual_update']=page.evaluate('({before:Journey.trace.tape.v[Journey.trace.loss],after:Journey.after.tape.v[Journey.after.loss],updates:Journey.model.updates})')
    page.screenshot(path=str(ROOT/'validation/guided-learning.png'),full_page=True)
    check('no arbitrary number ticker',page.evaluate('Lab.scene.particles.length')==0)
    page.locator('#journey-mode').click();check('advanced workshop remains reachable',page.locator('#train').is_visible());page.locator('#journey-mode').click()
    page.locator('#j-flat').click();check('2D explanation works',page.locator('#fallback').is_visible())
    page.locator('#j-infer').click();page.locator('#j-input').fill('🙂 inconnu');page.locator('#j-next').click();page.locator('#j-next').click();check('unknown characters explicit',page.evaluate('Journey.trace.tokens.includes(1)'))
    for width in [390,768,1280]:
        page.set_viewport_size({'width':width,'height':1000});check('no horizontal overflow '+str(width),page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
    page.locator('#j-input').fill('');page.locator('#j-next').click();check('empty text safe',page.evaluate('Journey.trace.tokens[0]===0'))
    fallback=b.new_page();fallback.on('pageerror',lambda e:report['errors'].append(str(e)));fallback.add_init_script("const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...rest){if(type.startsWith('webgl'))return null;return original.call(this,type,...rest);};");fallback.goto(BASE);fallback.wait_for_function('!!window.Journey');check('automatic guided fallback without WebGL',fallback.locator('#fallback').is_visible());fallback.locator('#j-next').click();check('fallback shows tokenization cards',fallback.locator('.j-flat-card').count()>=3);fallback.close()
    check('no runtime errors',not report['errors'])
    report['browser']=b.version;b.close()
(ROOT/'validation/journey.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(str(len(report['checks']))+' guided checks passed')
